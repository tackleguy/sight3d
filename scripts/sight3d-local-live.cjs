// Optional live verification; requires an already-running local model server.
const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({ headless:true, args:['--enable-unsafe-swiftshader'] });
 const page = await browser.newPage({ viewport:{width:1440,height:1000} });
 page.setDefaultTimeout(20000);
 page.on('response', async response => { if(response.url().endsWith('/chat/completions')) { try { const data=await response.json(); console.log('Local response:', data.choices?.[0]?.finish_reason, data.choices?.[0]?.message?.tool_calls?.map(c=>c.function.name), data.error || ''); } catch {} } });
 const requests=[];page.on('request',r=>{if(r.method()==='POST')requests.push(r.url());});
 await page.goto('http://127.0.0.1:3001');
 await page.getByText('Start modeling',{exact:true}).click();
 await page.waitForFunction(()=>!!window.modelAPI);
 await page.getByRole('button',{name:'Close quick start',exact:true}).click();
 await page.getByRole('button',{name:'AI settings',exact:true}).click();
 await page.getByRole('button',{name:'Find local models',exact:true}).click();
 await page.getByText(/Connected ·/).waitFor();
 await page.screenshot({path:'.impeccable/review/local-settings.png'});
 await page.locator('.prefs-save').click();
 await page.getByRole('button',{name:'Learn',exact:true}).click();
 await page.locator('#ai-prompt-input').fill('In one short sentence, what does Push/Pull do?');
 await page.getByRole('button',{name:'Send',exact:true}).click();
 await page.waitForFunction(()=> !document.querySelector('.ai-progress'),{},{timeout:200000});
 const error=await page.locator('.ai-chat-error').allTextContents();assert.deepEqual(error,[]);
 assert.ok((await page.locator('.ai-chat-msg-assistant').innerText()).length>20);
 await page.screenshot({path:'.impeccable/review/local-ai.png'});
 console.log('LOCAL LEARN:',await page.locator('.ai-chat-msg-assistant').innerText());
 await page.getByRole('button',{name:'Build',exact:true}).click();
 await page.locator('#ai-prompt-input').fill('Create a 1 meter cube at the origin.');
 await page.getByRole('button',{name:'Send',exact:true}).click();
 await page.waitForFunction(()=> !document.querySelector('.ai-progress'),{},{timeout:200000});
 console.log('LOCAL BUILD:',await page.locator('.ai-chat-msg-assistant').allTextContents());
 console.log('BUILD ERRORS:',await page.locator('.ai-chat-error').allTextContents());
 const faces=await page.evaluate(()=>window.modelAPI.getAllFaces().length);
 console.log('FACES:',faces);
 assert.ok(faces>=6,'Local model should create a cube through a real tool call');
 assert.ok(requests.every(url=>new URL(url).hostname==='127.0.0.1'));
 console.log('PASS: real local model discovery, settings, Learn response, Build geometry, loopback-only requests.');
 await page.screenshot({path:'.impeccable/review/local-build.png'});
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
